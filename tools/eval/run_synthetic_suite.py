#!/usr/bin/env python3
"""Runs the configuration comparison on every labelled synthetic scenario and writes one combined report.

usage: run_synthetic_suite.py --exe build/netsentinel [--prototype-exe PATH] --out results/synthetic [--report docs/evidence/synthetic_scenarios_linux.md]
Synthetic scenarios supplement CICIDS2017; they are designed tests of specific behaviours (see make_scenarios.py).
"""
import argparse, json, os, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__))
SCEN = ["s1_step", "s2_sustained", "s3_slow_ramp", "s4_legit_shift", "s5_idle_gap", "s6_quiet_host_scan"]
WHAT = {"s1_step": "10-window volume step with port scan",
        "s2_sustained": "100-window sustained flood (absorption, recovery limit)",
        "s3_slow_ramp": "slow ramp +2%/window over 120 windows (method limitation)",
        "s4_legit_shift": "legitimate permanent 1.5x shift, no attack (lockout cost of the gated baseline)",
        "s5_idle_gap": "10-minute idle gap, then a 5-window scan (idle windows, idle-gap cap)",
        "s6_quiet_host_scan": "near-constant host with rare jitter, one scan window (SD floor)"}

def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--exe", required=True); ap.add_argument("--prototype-exe", "--r0-exe", dest="prototype_exe")
    ap.add_argument("--out", required=True); ap.add_argument("--report"); a = ap.parse_args()
    sc = os.path.join(a.out, "scenarios"); os.makedirs(sc, exist_ok=True)
    subprocess.run([sys.executable, os.path.join(HERE, "make_scenarios.py"), sc], check=True)
    lines = ["# Synthetic configuration comparison (supplement to CICIDS2017)", "",
             "Generated by tools/eval/run_synthetic_suite.py. Window-level metrics, mixed windows excluded; warm-up (20) and",
             "unscored windows excluded. original_prototype = unmodified original prototype (commit f0e39c0). All runs on the machine named at the end.", ""]
    env = None
    for s in SCEN:
        out = os.path.join(a.out, s)
        cmd = [sys.executable, os.path.join(HERE, "run_comparison.py"), "--exe", a.exe, "--pcap", os.path.join(sc, s + ".pcap"),
               "--intervals", os.path.join(sc, s + "_labels.csv"), "--out", out, "--with-sensitivity", "--no-hash"]
        if a.prototype_exe: cmd += ["--prototype-exe", a.prototype_exe]
        subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL)
        M = json.load(open(os.path.join(out, "metrics.json")))
        lines += ["## %s: %s" % (s, WHAT[s]), "", "| config | TP | FP | FN | TN | recall | precision | false alarms/h | events detected |",
                  "|---|---|---|---|---|---|---|---|---|"]
        for r in M:
            p = r["primary"]; ev = r["events"]
            f = lambda x: "n/a" if x is None else "%.3f" % x
            lines.append("| %s | %d | %d | %d | %d | %s | %s | %s | %d/%d |" % (r["name"], p["TP"], p["FP"], p["FN"], p["TN"], f(p["recall"]),
                         f(p["precision"]), "n/a" if p["false_alarms_per_hour"] is None else "%.1f" % p["false_alarms_per_hour"],
                         sum(e["detected"] for e in ev), len(ev)))
        lines.append("")
        env = open(os.path.join(out, "environment.txt")).read()
    lines += ["## Environment (last run)", "", "```", env.strip(), "```", ""]
    text = "\n".join(lines)
    open(os.path.join(a.out, "synthetic_report.md"), "w").write(text)
    if a.report:
        os.makedirs(os.path.dirname(a.report), exist_ok=True); open(a.report, "w").write(text)
    print(text)

if __name__ == "__main__":
    main()
